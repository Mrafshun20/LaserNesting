    fun isPersian(language: String): Boolean = when (language) {
        "en" -> false
        "system" -> java.util.Locale.getDefault().language == "fa"
        else -> true
    }

    fun get(key: String, language: String): String {
        val table = if (isPersian(language)) fa else en
        return table[key] ?: en[key] ?: key
    }
